import { useState, useEffect } from 'react';

export function useLanguage() {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('smartgn_selected_language') || 'EN';
  });

  useEffect(() => {
    const handleLangChange = () => {
      setLang(localStorage.getItem('smartgn_selected_language') || 'EN');
    };
    window.addEventListener('smartgn-language-change', handleLangChange);
    window.addEventListener('storage', handleLangChange);
    return () => {
      window.removeEventListener('smartgn-language-change', handleLangChange);
      window.removeEventListener('storage', handleLangChange);
    };
  }, []);

  const changeLanguage = (newLang) => {
    localStorage.setItem('smartgn_selected_language', newLang);
    setLang(newLang);
    window.dispatchEvent(new Event('smartgn-language-change'));
  };

  return { lang, changeLanguage };
}

